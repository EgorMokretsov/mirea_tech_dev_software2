"""Минимальный калькулятор для практической работы по CI/CD."""


def add(a, b):
    """Возвращает сумму двух чисел."""
    return a + b


def multiply(a, b):
    """Возвращает произведение двух чисел."""
    return a * b


if __name__ == "__main__":
    print(add(2, 3))
    print(multiply(2, 3))
__version__ = "1.0.0"
